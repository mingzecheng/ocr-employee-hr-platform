CREATE TABLE IF NOT EXISTS employee_contract (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    contract_no VARCHAR(64) NOT NULL UNIQUE,
    employee_id BIGINT NOT NULL,
    contract_type VARCHAR(32) NOT NULL,
    signed_on DATE NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    renewal_status VARCHAR(24) NOT NULL DEFAULT 'NOT_DUE',
    source_version_id BIGINT NULL,
    renewed_from_contract_id BIGINT NULL,
    notes VARCHAR(512) NULL,
    version_no INT NOT NULL DEFAULT 0,
    created_by BIGINT NOT NULL,
    updated_by BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_contract_employee_dates (employee_id, starts_on, ends_on),
    INDEX idx_contract_renewal_end (renewal_status, ends_on),
    CONSTRAINT fk_contract_employee FOREIGN KEY (employee_id) REFERENCES employee(id),
    CONSTRAINT fk_contract_archive_version FOREIGN KEY (source_version_id) REFERENCES archive_version(id),
    CONSTRAINT fk_contract_renewed_from FOREIGN KEY (renewed_from_contract_id) REFERENCES employee_contract(id),
    CONSTRAINT fk_contract_created_by FOREIGN KEY (created_by) REFERENCES sys_user(id),
    CONSTRAINT fk_contract_updated_by FOREIGN KEY (updated_by) REFERENCES sys_user(id),
    CONSTRAINT ck_contract_date_order CHECK (ends_on >= starts_on AND starts_on >= signed_on),
    CONSTRAINT ck_contract_renewal_status CHECK (renewal_status IN ('NOT_DUE', 'RENEWED', 'NOT_RENEWING'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
