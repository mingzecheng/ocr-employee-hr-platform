package com.hrplatform.auth;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;

import static org.assertj.core.api.Assertions.assertThat;

@SpringBootTest
@ActiveProfiles("test")
class SysUserMapperPersistenceTest {
    @Autowired
    private JdbcTemplate jdbcTemplate;
    @Autowired
    private SysUserMapper mapper;

    @BeforeEach
    void createTables() {
        jdbcTemplate.execute("DROP TABLE IF EXISTS sys_user_role");
        jdbcTemplate.execute("DROP TABLE IF EXISTS sys_user");
        jdbcTemplate.execute("DROP TABLE IF EXISTS sys_role");
        jdbcTemplate.execute("DROP TABLE IF EXISTS employee");
        jdbcTemplate.execute("CREATE TABLE employee (id BIGINT PRIMARY KEY, department_id BIGINT, status VARCHAR(24))");
        jdbcTemplate.execute("""
                CREATE TABLE sys_role (
                    id BIGINT PRIMARY KEY,
                    code VARCHAR(32) NOT NULL UNIQUE,
                    name VARCHAR(64) NOT NULL,
                    enabled BOOLEAN NOT NULL
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE sys_user (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username VARCHAR(64) NOT NULL UNIQUE,
                    password_hash VARCHAR(255) NOT NULL,
                    employee_id BIGINT,
                    department_id BIGINT,
                    enabled BOOLEAN NOT NULL
                )
                """);
        jdbcTemplate.execute("CREATE TABLE sys_user_role (user_id BIGINT, role_id BIGINT, PRIMARY KEY(user_id, role_id))");
        jdbcTemplate.update("INSERT INTO employee (id, department_id, status) VALUES (20, 3, 'ACTIVE'), (21, 3, 'INACTIVE')");
        jdbcTemplate.update("""
                INSERT INTO sys_role (id, code, name, enabled) VALUES
                    (1, 'SYSTEM_ADMIN', '系统管理员', TRUE), (2, 'EMPLOYEE', '员工', TRUE),
                    (3, 'OLD_ROLE', '旧角色', FALSE), (4, 'DEPT_MANAGER', '部门负责人', TRUE)
                """);
        jdbcTemplate.update("""
                INSERT INTO sys_user (id, username, password_hash, employee_id, department_id, enabled) VALUES
                    (10, 'sys', 'hash', NULL, NULL, TRUE), (11, 'staff', 'hash', 20, 3, TRUE)
                """);
        jdbcTemplate.update("INSERT INTO sys_user_role (user_id, role_id) VALUES (10, 1), (11, 2), (11, 3), (11, 4)");
    }

    @AfterEach
    void dropTables() {
        jdbcTemplate.execute("DROP TABLE IF EXISTS sys_user_role");
        jdbcTemplate.execute("DROP TABLE IF EXISTS sys_user");
        jdbcTemplate.execute("DROP TABLE IF EXISTS sys_role");
        jdbcTemplate.execute("DROP TABLE IF EXISTS employee");
    }

    @Test
    void adminRowsNeverExposePasswordAndDisabledRolesAreNotEffective() {
        AdminUserRow row = mapper.listAdminUsers(0, 20).stream()
                .filter(user -> user.id().equals(11L)).findFirst().orElseThrow();

        assertThat(row.username()).isEqualTo("staff");
        assertThat(mapper.findRoles(11L)).containsExactly("DEPT_MANAGER", "EMPLOYEE");
        assertThat(mapper.listEnabledRoles()).extracting(AdminRoleOption::code)
                .containsExactly("DEPT_MANAGER", "EMPLOYEE", "SYSTEM_ADMIN");
    }

    @Test
    void lookupByIdReturnsCurrentAccountBinding() {
        SysUser user = mapper.findById(11L);

        assertThat(user.username()).isEqualTo("staff");
        assertThat(user.employeeId()).isEqualTo(20L);
        assertThat(user.departmentId()).isEqualTo(3L);
        assertThat(user.enabled()).isTrue();
    }

    @Test
    void roleReplacementAndSystemAdminLockQueriesMatchCurrentState() {
        assertThat(mapper.lockRoleIdByCode("SYSTEM_ADMIN")).isEqualTo(1L);
        assertThat(mapper.countEnabledSystemAdmins()).isEqualTo(1L);
        assertThat(mapper.deleteUserRoles(11L)).isEqualTo(3);
        assertThat(mapper.insertUserRole(11L, "SYSTEM_ADMIN")).isEqualTo(1);
        assertThat(mapper.findRoles(11L)).containsExactly("SYSTEM_ADMIN");
        assertThat(mapper.findActiveEmployee(20L).departmentId()).isEqualTo(3L);
        assertThat(mapper.findActiveEmployee(21L)).isNull();
    }

    @Test
    void employeeTransferSynchronizesAccountDepartmentAndRemovesManagerRole() {
        assertThat(mapper.updateDepartmentForEmployee(20L, 8L)).isEqualTo(1);
        assertThat(jdbcTemplate.queryForObject("SELECT department_id FROM sys_user WHERE id = 11", Long.class))
                .isEqualTo(8L);

        assertThat(mapper.deleteUserRoleForEmployee(20L, "DEPT_MANAGER")).isEqualTo(1);
        assertThat(mapper.findRoles(11L)).containsExactly("EMPLOYEE");
        assertThat(mapper.findRoles(10L)).containsExactly("SYSTEM_ADMIN");
    }
}
