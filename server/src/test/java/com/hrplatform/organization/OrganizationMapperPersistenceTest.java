package com.hrplatform.organization;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;

import static org.assertj.core.api.Assertions.assertThat;

@SpringBootTest
@ActiveProfiles("test")
class OrganizationMapperPersistenceTest {
    @Autowired
    private JdbcTemplate jdbcTemplate;
    @Autowired
    private OrganizationMapper mapper;

    @BeforeEach
    void createTables() {
        jdbcTemplate.execute("DROP TABLE IF EXISTS org_position");
        jdbcTemplate.execute("DROP TABLE IF EXISTS employee");
        jdbcTemplate.execute("DROP TABLE IF EXISTS org_department");
        jdbcTemplate.execute("""
                CREATE TABLE org_department (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    code VARCHAR(32) NOT NULL UNIQUE,
                    name VARCHAR(128) NOT NULL,
                    parent_id BIGINT,
                    manager_employee_id BIGINT,
                    sort_order INT NOT NULL,
                    enabled BOOLEAN NOT NULL
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE org_position (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    department_id BIGINT NOT NULL,
                    code VARCHAR(32) NOT NULL,
                    name VARCHAR(128) NOT NULL,
                    enabled BOOLEAN NOT NULL,
                    UNIQUE (department_id, code)
                )
                """);
        jdbcTemplate.execute("CREATE TABLE employee (id BIGINT PRIMARY KEY, department_id BIGINT, status VARCHAR(24))");
        jdbcTemplate.update("""
                INSERT INTO org_department (id, code, name, parent_id, manager_employee_id, sort_order, enabled)
                VALUES (1, 'OPS', '运营部', NULL, NULL, 1, TRUE), (2, 'OLD', '停用部门', NULL, NULL, 2, FALSE)
                """);
        jdbcTemplate.execute("ALTER TABLE org_department ALTER COLUMN id RESTART WITH 3");
        jdbcTemplate.update("""
                INSERT INTO org_position (id, department_id, code, name, enabled)
                VALUES (10, 1, 'OPS-A', '运营专员', TRUE), (11, 1, 'OPS-B', '旧岗位', FALSE),
                       (12, 2, 'OLD-A', '停用部门岗位', TRUE)
                """);
        jdbcTemplate.update("INSERT INTO employee (id, department_id, status) VALUES (20, 1, 'ACTIVE')");
    }

    @AfterEach
    void dropTables() {
        jdbcTemplate.execute("DROP TABLE IF EXISTS org_position");
        jdbcTemplate.execute("DROP TABLE IF EXISTS employee");
        jdbcTemplate.execute("DROP TABLE IF EXISTS org_department");
    }

    @Test
    void businessOptionsHideDisabledDepartmentsAndPositionsWhileAdminViewsKeepThem() {
        assertThat(mapper.listEnabledDepartments()).extracting(DepartmentNode::code).containsExactly("OPS");
        assertThat(mapper.listEnabledPositions(1L)).extracting(PositionOption::code).containsExactly("OPS-A");
        assertThat(mapper.listEnabledPositions(2L)).isEmpty();
        assertThat(mapper.listAllDepartments()).extracting(DepartmentAdminView::code).containsExactly("OPS", "OLD");
        assertThat(mapper.listDepartmentPositions(1L)).extracting(PositionAdminView::enabled)
                .containsExactlyInAnyOrder(true, false);
        assertThat(mapper.isEnabledPosition(12L, 2L)).isFalse();
    }

    @Test
    void departmentAndPositionWritesUseTheirDepartmentAndPreserveActiveBindings() {
        DepartmentMutationRequest department = new DepartmentMutationRequest("OPS-CHILD", "运营支持", 1L,
                20L, 3, true);
        assertThat(mapper.departmentCodeExists("OPS", null)).isTrue();
        assertThat(mapper.departmentCodeExists("OPS", 1L)).isFalse();
        assertThat(mapper.isActiveEmployee(20L)).isTrue();
        assertThat(mapper.hasEnabledChildren(1L)).isFalse();
        assertThat(mapper.hasActiveEmployees(1L)).isTrue();

        assertThat(mapper.insertDepartment(department)).isEqualTo(1);
        DepartmentAdminView inserted = mapper.findDepartmentByCode("OPS-CHILD");
        assertThat(inserted.parentId()).isEqualTo(1L);
        assertThat(inserted.managerEmployeeId()).isEqualTo(20L);
        assertThat(mapper.updateDepartment(inserted.id(), new DepartmentMutationRequest("OPS-CHILD", "运营支持一部",
                1L, 20L, 4, true))).isEqualTo(1);
        assertThat(mapper.findDepartment(inserted.id()).name()).isEqualTo("运营支持一部");

        PositionMutationRequest position = new PositionMutationRequest("OPS-C", "运营协调员", true);
        assertThat(mapper.positionCodeExists(1L, "OPS-A", null)).isTrue();
        assertThat(mapper.positionCodeExists(1L, "OPS-A", 10L)).isFalse();
        assertThat(mapper.insertPosition(1L, position)).isEqualTo(1);
        PositionAdminView savedPosition = mapper.findPositionByDepartmentAndCode(1L, "OPS-C");
        assertThat(savedPosition.departmentId()).isEqualTo(1L);
        assertThat(mapper.updatePosition(1L, savedPosition.id(),
                new PositionMutationRequest("OPS-C", "运营协调专员", false))).isEqualTo(1);
        assertThat(mapper.findPosition(savedPosition.id()).enabled()).isFalse();
    }

    @Test
    void transferClearsEveryDepartmentAssignmentForFormerManager() {
        jdbcTemplate.update("UPDATE org_department SET manager_employee_id = 20 WHERE id IN (1, 2)");

        assertThat(mapper.clearManagerAssignmentForEmployee(20L)).isEqualTo(2);
        assertThat(jdbcTemplate.queryForList(
                "SELECT manager_employee_id FROM org_department WHERE id IN (1, 2)", Long.class))
                .containsOnlyNulls();
    }
}
